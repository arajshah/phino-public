"""
DynaCLIP Dataset & DataLoader: Contrastive pairs with dynamics similarity labels.

Supports hard-negative mining, DINOv2 embedding pre-computation, and the
Invisible Physics test split. Uses REAL images from DomainNet/COCO.
"""

import json
import logging
import random
from pathlib import Path
from typing import Optional
import numpy as np
import torch
from torch.utils.data import Dataset, DataLoader, DistributedSampler
import torchvision.transforms as T
from train.data.splits import split_metadata_by_asset

logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Image transforms
# ---------------------------------------------------------------------------
def get_train_transform(img_size: int = 224) -> T.Compose:
    return T.Compose([
        T.RandomResizedCrop(img_size, scale=(0.8, 1.0)),
        T.RandomHorizontalFlip(p=0.5),
        T.ColorJitter(brightness=0.1, contrast=0.1, saturation=0.1, hue=0.05),
        T.ToTensor(),
        T.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225]),
    ])


def resolve_image_path(data_dir: Path, stored: str) -> Optional[Path]:
    """Robustly locate an image given a path stored in metadata.

    Handles all of: an absolute path, a path already relative to CWD (e.g.
    "data/phino_data/images/x.png"), a path relative to data_dir
    ("images/x.png"), and a bare basename. Returns None if nothing exists.
    Without this, a stored "data/phino_data/images/x.png" gets data_dir
    prepended again -> a non-existent path -> a black fallback image for every
    sample (which silently collapses contrastive training).
    """
    p = Path(stored)
    for c in (p, data_dir / p, data_dir / "images" / p.name):
        if c.exists():
            return c
    return None


def get_eval_transform(img_size: int = 224) -> T.Compose:
    return T.Compose([
        T.Resize(img_size),
        T.CenterCrop(img_size),
        T.ToTensor(),
        T.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225]),
    ])


# ---------------------------------------------------------------------------
# Main training dataset: contrastive pairs with dynamics similarity
# ---------------------------------------------------------------------------
class DynaCLIPContrastiveDataset(Dataset):
    """Dataset returning pairs (img_i, img_j, dynamics_similarity).

    Pair mining:
      - 30% hard negatives: same image but different physics (high visual sim, varying dyn sim)
      - 30% hard positives: different image but similar physics
      - 40% random
    """

    def __init__(
        self,
        data_dir: str,
        split: str = "train",
        transform: Optional[T.Compose] = None,
        num_pairs: int = 200_000,
        hard_neg_ratio: float = 0.3,
        hard_pos_ratio: float = 0.3,
        dino_embeddings_path: Optional[str] = None,
        similarity_path: Optional[str] = None,
        seed: int = 42,
        random_views: bool = True,
    ):
        super().__init__()
        self.data_dir = Path(data_dir)
        self.split = split
        self.transform = transform or get_train_transform()
        self.num_pairs = num_pairs
        # Train on a RANDOM view of each object (view-invariant physical awareness);
        # also makes same-object/different-physics hard negatives learnable (the two
        # views differ, so the encoder can assign them different embeddings).
        self.random_views = random_views
        self.hard_neg_ratio = hard_neg_ratio
        self.hard_pos_ratio = hard_pos_ratio
        self.rng = np.random.default_rng(seed)

        # Load metadata - MUST exist (generated by generation.py)
        meta_path = self.data_dir / "metadata.json"
        if not meta_path.exists():
            raise FileNotFoundError(
                f"metadata.json not found at {meta_path}. "
                "Run data generation first: python -m dynaclip.data.generation"
            )
        with open(meta_path) as f:
            self.metadata = json.load(f)
        logger.info(f"Loaded {len(self.metadata)} entries from {meta_path}")

        # Build image_group index for hard mining
        self._group_index = {}
        for i, entry in enumerate(self.metadata):
            grp = entry.get("image_group", i)
            self._group_index.setdefault(grp, []).append(i)

        # Load dynamics similarity matrix (optional, from generation.py)
        self.sim_lookup = {}
        sim_path = similarity_path or str(self.data_dir / "similarity_matrix.npz")
        if Path(sim_path).exists():
            data = np.load(sim_path)
            pairs_arr = data["pairs"]
            sims_arr = data["similarities"]
            for k in range(len(pairs_arr)):
                i, j = int(pairs_arr[k, 0]), int(pairs_arr[k, 1])
                self.sim_lookup[(i, j)] = float(sims_arr[k])
                self.sim_lookup[(j, i)] = float(sims_arr[k])
            logger.info(f"Loaded {len(pairs_arr)} similarity pairs")

        # Load pre-computed DINOv2 embeddings (optional, for pair mining)
        self.dino_embeddings = None
        if dino_embeddings_path and Path(dino_embeddings_path).exists():
            data = np.load(dino_embeddings_path)
            self.dino_embeddings = data["embeddings"]

        # Preload all trajectory fingerprints into memory (for fast hard mining)
        n_hard_neg_check = int(num_pairs * hard_neg_ratio)
        n_hard_pos_check = int(num_pairs * hard_pos_ratio)
        if n_hard_neg_check > 0 or n_hard_pos_check > 0:
            self._preload_trajectories()

        # Mine pairs
        self.pairs = self._mine_pairs()

    def _mine_pairs(self) -> list:
        """Mine contrastive pairs based on dynamics and visual similarity."""
        n = len(self.metadata)

        n_hard_neg = int(self.num_pairs * self.hard_neg_ratio)
        n_hard_pos = int(self.num_pairs * self.hard_pos_ratio)

        # Fast path: when no hard mining is needed and we have precomputed pairs,
        # use them directly instead of re-mining (avoids expensive on-the-fly
        # trajectory similarity computation for pairs not in sim_lookup)
        if n_hard_neg == 0 and n_hard_pos == 0 and self.sim_lookup:
            logger.info(f"Using {len(self.sim_lookup)//2} precomputed pairs directly (no hard mining)")
            # Convert sim_lookup to pairs list (deduplicate symmetric entries)
            seen = set()
            pairs = []
            for (i, j), sim in self.sim_lookup.items():
                key = (min(i, j), max(i, j))
                if key not in seen:
                    seen.add(key)
                    pairs.append((i, j, sim))
            # Shuffle and truncate/repeat to match num_pairs
            self.rng.shuffle(pairs)
            if len(pairs) >= self.num_pairs:
                pairs = pairs[:self.num_pairs]
            else:
                # Repeat pairs to fill num_pairs
                repeats = (self.num_pairs // len(pairs)) + 1
                pairs = (pairs * repeats)[:self.num_pairs]
            return pairs

        pairs = []
        n_random = self.num_pairs - n_hard_neg - n_hard_pos

        group_keys = list(self._group_index.keys())

        # Hard negatives: SAME image, DIFFERENT physics → same visual, different dynamics
        for _ in range(n_hard_neg):
            grp = self.rng.choice(group_keys)
            members = self._group_index[grp]
            if len(members) >= 2:
                i, j = self.rng.choice(members, size=2, replace=False)
            else:
                i, j = self.rng.integers(0, n, size=2)
            dyn_sim = self._get_dynamics_similarity(i, j)
            pairs.append((int(i), int(j), dyn_sim))

        # Hard positives: DIFFERENT image, SIMILAR physics
        for _ in range(n_hard_pos):
            i = int(self.rng.integers(0, n))
            mass_i = self.metadata[i]["mass"]
            fric_i = self.metadata[i]["static_friction"]
            rest_i = self.metadata[i]["restitution"]
            grp_i = self.metadata[i].get("image_group", i)
            # Find candidates with similar physics but different image
            best_j, best_dist = int(self.rng.integers(0, n)), float('inf')
            for _ in range(20):  # sample 20 candidates
                j = int(self.rng.integers(0, n))
                grp_j = self.metadata[j].get("image_group", j)
                if grp_j == grp_i:
                    continue
                dist = abs(np.log(self.metadata[j]["mass"] + 1e-6) - np.log(mass_i + 1e-6)) + \
                       abs(self.metadata[j]["static_friction"] - fric_i) + \
                       abs(self.metadata[j]["restitution"] - rest_i)
                if dist < best_dist:
                    best_j, best_dist = j, dist
            dyn_sim = self._get_dynamics_similarity(i, best_j)
            pairs.append((i, best_j, dyn_sim))

        # Random pairs
        for _ in range(n_random):
            i, j = self.rng.integers(0, n, size=2)
            dyn_sim = self._get_dynamics_similarity(int(i), int(j))
            pairs.append((int(i), int(j), dyn_sim))

        return pairs

    def _get_dynamics_similarity(self, i: int, j: int) -> float:
        """Get dynamics similarity between two data points."""
        if (i, j) in self.sim_lookup:
            return self.sim_lookup[(i, j)]
        return self._compute_proxy_similarity(i, j)

    def _preload_trajectories(self) -> None:
        """Load all trajectory fingerprints into a single numpy array.

        Uses a consolidated .npy cache file at <data_dir>/all_trajectories.npy
        that is built once and reused by all ranks. This avoids the massive
        disk I/O contention of 6 ranks each loading 100K separate .npz files.
        """
        import time
        import os
        n = len(self.metadata)
        cache_file = self.data_dir / "all_trajectories.npy"

        # Try to load consolidated cache
        if cache_file.exists():
            t0 = time.time()
            arr = np.load(cache_file, mmap_mode="r")
            logger.info(f"Loaded consolidated trajectory cache {arr.shape} in {time.time()-t0:.1f}s")
            self._traj_array = arr
            return

        # Rank-0 only builds cache; other ranks wait for file
        is_rank_0 = (int(os.environ.get("RANK", 0)) == 0)
        if not is_rank_0:
            logger.info(f"Waiting for rank 0 to build trajectory cache at {cache_file}...")
            while not cache_file.exists():
                time.sleep(5)
            time.sleep(2)  # Ensure file fully written
            arr = np.load(cache_file, mmap_mode="r")
            logger.info(f"Loaded consolidated trajectory cache {arr.shape}")
            self._traj_array = arr
            return

        # Rank 0: build cache
        t0 = time.time()
        logger.info(f"Building consolidated trajectory cache for {n} entries...")
        all_trajs = []
        for idx in range(n):
            fp_path = self.metadata[idx].get("fingerprint_path")
            traj = None
            if fp_path:
                fp = Path(fp_path)
                if not fp.is_absolute() or not fp.exists():
                    fp = self.data_dir / "fingerprints" / fp.name
                if fp.exists():
                    traj = np.load(fp)["flat_trajectory"]
            if traj is None:
                fp_rel = self.data_dir / "fingerprints" / f"fp_{idx:06d}.npz"
                if fp_rel.exists():
                    traj = np.load(fp_rel)["flat_trajectory"]
            if traj is None:
                raise RuntimeError(f"Missing fingerprint for idx {idx}")
            all_trajs.append(traj)
            if (idx + 1) % 10000 == 0:
                logger.info(f"  loaded {idx+1}/{n}, {(idx+1)/(time.time()-t0):.0f} tr/s")

        # Stack into one array, save atomically
        # (np.save appends ".npy" if not present, so we name the tmp without ".npy")
        arr = np.stack(all_trajs)
        tmp = self.data_dir / "all_trajectories_tmp"  # np.save -> all_trajectories_tmp.npy
        np.save(tmp, arr)
        os.replace(str(tmp) + ".npy", cache_file)
        logger.info(f"Saved consolidated cache {arr.shape} to {cache_file} ({time.time()-t0:.1f}s)")
        self._traj_array = arr

    def _get_trajectory(self, idx: int) -> np.ndarray:
        """Get trajectory fingerprint for an entry, with caching.

        Three-level lookup:
          1. In-memory cache (instant)
          2. Precomputed fingerprint .npz on disk (fast)
          3. On-the-fly computation via analytical physics engine (~10ms)
        """
        # Fast path: consolidated array
        if hasattr(self, '_traj_array') and self._traj_array is not None:
            return self._traj_array[idx]

        if not hasattr(self, '_traj_cache'):
            self._traj_cache = {}

        if idx in self._traj_cache:
            return self._traj_cache[idx]

        # Load precomputed fingerprint from disk (always written by generation.py)
        fp_path = self.metadata[idx].get("fingerprint_path")
        if fp_path:
            fp = Path(fp_path)
            # Handle absolute paths that don't exist (data moved to different machine)
            if not fp.is_absolute() or not fp.exists():
                fp = self.data_dir / "fingerprints" / fp.name
            if fp.exists():
                traj = np.load(fp)["flat_trajectory"]
                self._traj_cache[idx] = traj
                return traj

        raise RuntimeError(
            f"Missing trajectory fingerprint for idx {idx}; re-run data generation."
        )

    def _compute_proxy_similarity(self, i: int, j: int) -> float:
        """Compute dynamics similarity from physics trajectories.

        Uses the analytical physics engine to generate trajectories for both
        entries and computes L2-based similarity. This replaces the old
        parameter-distance proxy with actual trajectory similarity.
        """
        traj_i = self._get_trajectory(i)
        traj_j = self._get_trajectory(j)
        # Prefer the fitted trajectory normalizer (identical stats to the
        # precomputed similarity matrix); fall back to raw MSE if absent.
        if not hasattr(self, "_normalizer"):
            from train.data.mujoco_engine import TrajectoryNormalizer
            norm_path = self.data_dir / "traj_norm.npz"
            self._normalizer = (TrajectoryNormalizer.load(str(norm_path))
                                if norm_path.exists() else None)
        if self._normalizer is not None:
            return self._normalizer.similarity(traj_i, traj_j)
        from train.data.generation import compute_dynamics_similarity_l2
        return compute_dynamics_similarity_l2(traj_i, traj_j)

    def __len__(self) -> int:
        return len(self.pairs)

    def __getitem__(self, idx: int) -> dict:
        i, j, dyn_sim = self.pairs[idx]
        img_i = self._load_image(i)
        img_j = self._load_image(j)

        # Physics vectors: [log(mass), friction, restitution] for RnC loss
        mi, mj = self.metadata[i], self.metadata[j]
        physics_i = torch.tensor([
            np.log(mi["mass"] + 1e-6),
            mi["static_friction"],
            mi["restitution"],
        ], dtype=torch.float32)
        physics_j = torch.tensor([
            np.log(mj["mass"] + 1e-6),
            mj["static_friction"],
            mj["restitution"],
        ], dtype=torch.float32)

        return {
            "img_i": img_i,
            "img_j": img_j,
            "dynamics_similarity": torch.tensor(dyn_sim, dtype=torch.float32),
            "physics_i": physics_i,
            "physics_j": physics_j,
            "mass_i": torch.tensor(mi["mass"], dtype=torch.float32),
            "mass_j": torch.tensor(mj["mass"], dtype=torch.float32),
            "friction_i": torch.tensor(mi["static_friction"], dtype=torch.float32),
            "friction_j": torch.tensor(mj["static_friction"], dtype=torch.float32),
            "restitution_i": torch.tensor(mi["restitution"], dtype=torch.float32),
            "restitution_j": torch.tensor(mj["restitution"], dtype=torch.float32),
            "idx_i": i,
            "idx_j": j,
        }

    def _load_image(self, idx: int) -> torch.Tensor:
        """Load a REAL image from disk (a random view of the object if enabled)."""
        entry = self.metadata[idx]
        stored = entry["image_path"]
        if self.random_views:
            views = entry.get("view_paths")
            if views:
                stored = random.choice(views)
        img_path = resolve_image_path(self.data_dir, stored)
        if img_path is None:
            raise FileNotFoundError(f"image not found for idx {idx}: {stored}")
        from PIL import Image
        img = Image.open(img_path).convert("RGB")
        return self.transform(img)


# ---------------------------------------------------------------------------
# Invisible Physics test dataset
# ---------------------------------------------------------------------------
class InvisiblePhysicsDataset(Dataset):
    """Test pairs: same image, different physics properties.

    The key insight: both images look IDENTICAL to a standard vision model,
    but DynaCLIP should produce different embeddings because it has learned
    to encode physics-dependent representations.

    We load the SAME real image for both views but provide different physics labels.
    """

    def __init__(
        self,
        data_dir: str,
        test_file: str = "invisible_physics_test.json",
        transform: Optional[T.Compose] = None,
    ):
        super().__init__()
        self.data_dir = Path(data_dir)
        self.transform = transform or get_eval_transform()

        test_path = self.data_dir / test_file
        if not test_path.exists():
            raise FileNotFoundError(
                f"Invisible physics test file not found: {test_path}. "
                "Run data generation first."
            )
        with open(test_path) as f:
            self.pairs = json.load(f)
        logger.info(f"Loaded {len(self.pairs)} invisible physics test pairs")

    def __len__(self) -> int:
        return len(self.pairs)

    def __getitem__(self, idx: int) -> dict:
        pair = self.pairs[idx]
        img_path = resolve_image_path(self.data_dir, pair["image_path"])
        if img_path is None:
            raise FileNotFoundError(f"Test image not found: {pair['image_path']}")

        from PIL import Image
        img = Image.open(img_path).convert("RGB")
        img_tensor = self.transform(img)

        pa = pair["physics_a"]
        pb = pair["physics_b"]
        return {
            "img_a": img_tensor,      # Same image for both
            "img_b": img_tensor,      # Visually identical
            "mass_a": torch.tensor(pa["mass"], dtype=torch.float32),
            "mass_b": torch.tensor(pb["mass"], dtype=torch.float32),
            "friction_a": torch.tensor(pa["static_friction"], dtype=torch.float32),
            "friction_b": torch.tensor(pb["static_friction"], dtype=torch.float32),
            "restitution_a": torch.tensor(pa["restitution"], dtype=torch.float32),
            "restitution_b": torch.tensor(pb["restitution"], dtype=torch.float32),
            "heavier_label": torch.tensor(
                1 if pa["mass"] > pb["mass"] else 0, dtype=torch.long,
            ),
            "dynamics_similarity": torch.tensor(
                pair.get("dynamics_similarity", 0.5), dtype=torch.float32,
            ),
        }


# ---------------------------------------------------------------------------
# Linear probing dataset
# ---------------------------------------------------------------------------
class PhysicsProbeDataset(Dataset):
    """Dataset for linear probing: predict physics properties from frozen features."""

    def __init__(
        self,
        data_dir: str,
        split: str = "train",
        transform: Optional[T.Compose] = None,
        seed: int = 42,
    ):
        super().__init__()
        self.data_dir = Path(data_dir)
        self.transform = transform or get_eval_transform()
        self.rng = np.random.default_rng(seed)

        meta_path = self.data_dir / "metadata.json"
        if not meta_path.exists():
            raise FileNotFoundError(
                f"metadata.json not found at {meta_path}. "
                "Run data generation first."
            )
        with open(meta_path) as f:
            all_meta = json.load(f)

        # Keep all physics variants of each asset in one probe split.
        self.metadata = split_metadata_by_asset(all_meta, split=split, seed=seed)
        logger.info(f"PhysicsProbeDataset({split}): {len(self.metadata)} entries")

    def __len__(self) -> int:
        return len(self.metadata)

    def __getitem__(self, idx: int) -> dict:
        entry = self.metadata[idx]
        img_path = resolve_image_path(self.data_dir, entry["image_path"])
        if img_path is None:
            raise FileNotFoundError(
                f"probe image not found: {entry['image_path']}")
        from PIL import Image
        img = Image.open(img_path).convert("RGB")
        img_tensor = self.transform(img)

        return {
            "image": img_tensor,
            "mass": torch.tensor(entry["mass"], dtype=torch.float32),
            "static_friction": torch.tensor(entry["static_friction"], dtype=torch.float32),
            "restitution": torch.tensor(entry["restitution"], dtype=torch.float32),
            "category": entry.get("category", "unknown"),
        }


# ---------------------------------------------------------------------------
# DataLoader creation utilities
# ---------------------------------------------------------------------------
def create_contrastive_dataloader(
    data_dir: str,
    batch_size: int = 1024,
    num_workers: int = 8,
    distributed: bool = False,
    **kwargs,
) -> DataLoader:
    dataset = DynaCLIPContrastiveDataset(data_dir=data_dir, **kwargs)
    sampler = DistributedSampler(dataset) if distributed else None
    return DataLoader(
        dataset,
        batch_size=batch_size,
        shuffle=(sampler is None),
        sampler=sampler,
        num_workers=num_workers,
        pin_memory=True,
        drop_last=True,
        persistent_workers=(num_workers > 0),
    )


def create_probe_dataloader(
    data_dir: str,
    split: str = "train",
    batch_size: int = 256,
    num_workers: int = 4,
    seed: int = 42,
) -> DataLoader:
    dataset = PhysicsProbeDataset(data_dir=data_dir, split=split, seed=seed)
    return DataLoader(
        dataset,
        batch_size=batch_size,
        shuffle=(split == "train"),
        num_workers=num_workers,
        pin_memory=True,
    )
